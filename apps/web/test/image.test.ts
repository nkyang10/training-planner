import { describe, expect, it } from "vitest";
import { stripExif } from "../src/image";

const bytes = (...values: number[]): Uint8Array => Uint8Array.from(values);

describe("stripExif", () => {
  it("removes JPEG APP1 (EXIF) and keeps the scan data", () => {
    const jpeg = bytes(
      0xff, 0xd8, // SOI
      0xff, 0xe1, 0x00, 0x08, 0x45, 0x78, 0x69, 0x66, 0x00, 0x00, // APP1 "Exif\0\0" (length 8)
      0xff, 0xdb, 0x00, 0x04, 0x00, 0x01, // DQT
      0xff, 0xda, 0x00, 0x02, 0xaa, 0xbb, // SOS + data
    );
    const stripped = stripExif(jpeg, "image/jpeg");
    expect(Array.from(stripped)).toEqual([0xff, 0xd8, 0xff, 0xdb, 0x00, 0x04, 0x00, 0x01, 0xff, 0xda, 0x00, 0x02, 0xaa, 0xbb]);
  });

  it("removes the PNG eXIf chunk and keeps the rest", () => {
    const png = bytes(
      0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
      0x00, 0x00, 0x00, 0x00, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x00, // IHDR + CRC
      0x00, 0x00, 0x00, 0x03, 0x65, 0x58, 0x49, 0x66, 0x01, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00, // eXIf + CRC
      0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0x00, 0x00, 0x00, 0x00, // IEND + CRC
    );
    const stripped = stripExif(png, "image/png");
    expect(Array.from(stripped)).toEqual([
      0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
      0x00, 0x00, 0x00, 0x00, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0x00, 0x00, 0x00, 0x00,
    ]);
  });

  it("passes through webp and malformed bytes untouched", () => {
    const webp = bytes(0x52, 0x49, 0x46, 0x46, 0x01, 0x02);
    expect(stripExif(webp, "image/webp")).toBe(webp);
    expect(stripExif(bytes(1, 2, 3), "image/jpeg")).toEqual(bytes(1, 2, 3));
  });
});
